-- PostgreSQL schema, shared by the Rust engine (data path) and the Python web UI. Both apply this
-- file on start (serialized by an advisory lock); every statement is idempotent.
-- All integers are BIGINT: unix timestamps, sizes and nanosecond mtimes do not fit in 32 bits.

CREATE TABLE IF NOT EXISTS devices (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL UNIQUE,   -- namespace: /devices/<name>/ (or /sources/<name>/)
    kind           TEXT NOT NULL DEFAULT 'device',  -- device | source (sources have no usable token)
    token_hash     TEXT NOT NULL,          -- hex sha256 of the device token
    created_at     BIGINT NOT NULL,
    revoked_at     BIGINT,
    hostname       TEXT,
    os             TEXT,
    ip             TEXT,
    client_version TEXT,
    disk_total     BIGINT,
    disk_free      BIGINT,
    last_seen      BIGINT,                 -- last heartbeat or upload
    last_collected BIGINT                  -- last committed version
);

CREATE TABLE IF NOT EXISTS files (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id          BIGINT NOT NULL REFERENCES devices(id),
    path               TEXT NOT NULL,
    current_version_id BIGINT,
    deleted_at         BIGINT,
    UNIQUE (device_id, path)
);

CREATE TABLE IF NOT EXISTS versions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id    BIGINT NOT NULL REFERENCES files(id),
    root_hash  BYTEA NOT NULL,
    size       BIGINT NOT NULL,
    mtime      BIGINT NOT NULL,            -- unix nanoseconds
    mode       BIGINT NOT NULL DEFAULT 0,
    manifest   BYTEA NOT NULL,             -- concatenated 32-byte chunk hashes
    created_at BIGINT NOT NULL,
    pruned_at  BIGINT                      -- set when beyond the version count
);
CREATE INDEX IF NOT EXISTS versions_file ON versions(file_id, id);
CREATE INDEX IF NOT EXISTS versions_root ON versions(root_hash);

CREATE TABLE IF NOT EXISTS events (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id),
    path      TEXT NOT NULL,
    action    TEXT NOT NULL,               -- add | update | delete | rename
    ts        BIGINT NOT NULL,
    hash      TEXT,
    detail    TEXT                         -- e.g. old path of a rename
);
CREATE INDEX IF NOT EXISTS events_device ON events(device_id, id);

CREATE TABLE IF NOT EXISTS alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        TEXT NOT NULL,             -- device_offline | upload_error | disk_usage | source_failed | mirror_failed
    key         TEXT NOT NULL DEFAULT '',  -- e.g. device name
    message     TEXT NOT NULL,
    created_at  BIGINT NOT NULL,
    updated_at  BIGINT,                    -- last time the problem was reported again
    resolved_at BIGINT
);
CREATE UNIQUE INDEX IF NOT EXISTS alerts_open ON alerts(kind, key) WHERE resolved_at IS NULL;

-- Third-party sources collected by the engine itself. Each has a hidden devices row (kind = 'source')
-- that owns its files under /sources/<name>/.
CREATE TABLE IF NOT EXISTS sources (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,
    kind          TEXT NOT NULL,           -- gdrive
    config        TEXT NOT NULL,           -- JSON, includes credentials
    interval_secs BIGINT NOT NULL DEFAULT 86400,
    enabled       BIGINT NOT NULL DEFAULT 1,
    device_id     BIGINT NOT NULL REFERENCES devices(id),
    run_requested BIGINT NOT NULL DEFAULT 0,
    last_run_at   BIGINT,
    last_ok_at    BIGINT,
    last_status   TEXT,                    -- running | ok | partial | failed
    last_message  TEXT,
    created_at    BIGINT NOT NULL
);

-- What the engine already imported from a source: remote id -> path and version marker.
CREATE TABLE IF NOT EXISTS source_items (
    source_id      BIGINT NOT NULL REFERENCES sources(id) ON DELETE CASCADE,
    remote_id      TEXT NOT NULL,
    path           TEXT NOT NULL,
    remote_version TEXT NOT NULL,
    PRIMARY KEY (source_id, remote_id)
);

-- Offsite mirrors, driven by rclone. `options` is a JSON object of rclone backend options.
CREATE TABLE IF NOT EXISTS mirrors (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,
    remote_type   TEXT NOT NULL,           -- rclone backend: s3, sftp, local, ...
    options       TEXT NOT NULL,           -- JSON, includes credentials
    remote_path   TEXT NOT NULL,           -- bucket/prefix inside the remote
    interval_secs BIGINT NOT NULL DEFAULT 259200,
    keep_runs     BIGINT NOT NULL DEFAULT 3,
    enabled       BIGINT NOT NULL DEFAULT 1,
    run_requested BIGINT NOT NULL DEFAULT 0,
    last_run_at   BIGINT,
    last_ok_at    BIGINT,
    last_status   TEXT,                    -- running | ok | partial | failed
    last_message  TEXT,
    last_files    BIGINT,
    last_bytes    BIGINT,
    created_at    BIGINT NOT NULL
);

-- What is already on the mirror: the root hash of each file as last uploaded.
CREATE TABLE IF NOT EXISTS mirror_items (
    mirror_id BIGINT NOT NULL REFERENCES mirrors(id) ON DELETE CASCADE,
    device_id BIGINT NOT NULL,
    path      TEXT NOT NULL,
    root_hash BYTEA NOT NULL,
    PRIMARY KEY (mirror_id, device_id, path)
);

CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
