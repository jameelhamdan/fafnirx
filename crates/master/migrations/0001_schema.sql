-- The schema of the master's database. Later changes are new numbered files next to this one (see `platform/migrations.rs`).
-- Times are unix seconds unless a column says otherwise; ids of files, albums, tags, jobs and alerts are UUIDs.

CREATE EXTENSION IF NOT EXISTS pg_trgm WITH SCHEMA public;

-- Users and their logins. Only the hash of a session token is kept, so a copy of the database cannot be used to log in.
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,
    role          TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at    BIGINT NOT NULL,
    disabled_at   BIGINT,
    CONSTRAINT users_name_slug CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$' AND name !~ '^(con|prn|aux|nul|com[0-9]|lpt[0-9])(\.|$)'),
    CONSTRAINT users_role CHECK (role IN ('admin', 'normal', 'readonly'))
);

CREATE FUNCTION users_name_is_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.name <> OLD.name THEN
        RAISE EXCEPTION 'the name of a user cannot change';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER users_name_fixed BEFORE UPDATE OF name ON users FOR EACH ROW EXECUTE FUNCTION users_name_is_fixed();

CREATE TABLE sessions (
    token_hash TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX sessions_user ON sessions (user_id);
CREATE INDEX sessions_expires ON sessions (expires_at);

-- A device is a computer that sends files (kind `device`, with a token), a folder of a user (`local`: no token, and shared when
-- `shared_members` lists others), or the master files (`master`, id 0, no owner). Its `folder` (`<user>/<name>`, `_master`) names it
-- in the file store, the mirrors and the API; `public_id` is the address clients keep when it is renamed.
CREATE TABLE devices (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id      UUID NOT NULL DEFAULT gen_random_uuid(),
    user_id        BIGINT REFERENCES users(id),
    name           TEXT NOT NULL,
    kind           TEXT NOT NULL DEFAULT 'device',
    folder         TEXT NOT NULL,
    token_hash     TEXT NOT NULL,
    created_at     BIGINT NOT NULL,
    revoked_at     BIGINT,
    -- Which installation of the client holds the device now (see the lease in `devices/grpc.rs`).
    instance_id    TEXT,
    hostname       TEXT,
    os             TEXT,
    ip             TEXT,
    client_version TEXT,
    disk_total     BIGINT,
    disk_free      BIGINT,
    last_seen      BIGINT,
    last_collected BIGINT,
    -- What it holds, added up lazily (`devices/totals.rs`); stale until the next sum.
    file_count     BIGINT NOT NULL DEFAULT 0,
    total_bytes    BIGINT NOT NULL DEFAULT 0,
    deleted_files  BIGINT NOT NULL DEFAULT 0,
    totals_stale   BOOLEAN NOT NULL DEFAULT TRUE,
    totals_at      BIGINT,
    CONSTRAINT devices_kind CHECK (kind IN ('device', 'local', 'master')),
    CONSTRAINT devices_owner CHECK ((kind = 'master') = (user_id IS NULL)),
    CONSTRAINT devices_name_slug CHECK (kind = 'master' OR (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$' AND name !~ '^(con|prn|aux|nul|com[0-9]|lpt[0-9])(\.|$)'))
);
CREATE UNIQUE INDEX devices_folder ON devices (folder);
CREATE UNIQUE INDEX devices_public_id ON devices (public_id);
CREATE UNIQUE INDEX devices_user_name ON devices (user_id, name);
CREATE UNIQUE INDEX devices_token ON devices (token_hash) WHERE kind = 'device';

CREATE FUNCTION devices_set_folder() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.kind = 'master' THEN
        NEW.folder := '_master';
    ELSE
        NEW.folder := (SELECT name FROM users WHERE id = NEW.user_id) || '/' || NEW.name;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER devices_folder BEFORE INSERT ON devices FOR EACH ROW EXECUTE FUNCTION devices_set_folder();
CREATE TRIGGER devices_folder_renamed BEFORE UPDATE OF name ON devices FOR EACH ROW EXECUTE FUNCTION devices_set_folder();

CREATE FUNCTION devices_owner_is_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN
        RAISE EXCEPTION 'the owner of a device cannot change';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER devices_owner_fixed BEFORE UPDATE OF user_id ON devices FOR EACH ROW EXECUTE FUNCTION devices_owner_is_fixed();

-- The other users who use a folder of a user, each reading or reading and changing.
CREATE TABLE shared_members (
    folder_id  BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users(id),
    can_write  BOOLEAN NOT NULL DEFAULT TRUE,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (folder_id, user_id)
);
CREATE INDEX shared_members_user ON shared_members (user_id);

-- The one rule for what a user sees of the devices and folders: everything (an administrator), the master files, their own, and
-- the folders they were added to. Every query that scopes by user calls this.
CREATE FUNCTION visible(dev devices, uid BIGINT, everything BOOLEAN) RETURNS BOOLEAN LANGUAGE sql STABLE AS
$$ SELECT everything OR dev.kind = 'master' OR dev.user_id = uid
       OR EXISTS (SELECT 1 FROM shared_members m JOIN users o ON o.id = dev.user_id
                  WHERE m.folder_id = dev.id AND m.user_id = uid AND o.disabled_at IS NULL) $$;

-- Subfolders of the master files (device 0) that computers sync both ways. Never the master files as a whole.
CREATE TABLE master_folders (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id  UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
    prefix     TEXT NOT NULL UNIQUE CHECK (prefix <> '' AND prefix !~ '^/|/$|//'),
    created_at BIGINT NOT NULL
);

-- What each computer says about the folders attached to it, with every heartbeat (they replace the earlier ones).
CREATE TABLE device_folder_state (
    device_id  BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    folder     TEXT NOT NULL,
    files      BIGINT NOT NULL,
    bytes      BIGINT NOT NULL,
    last_cycle BIGINT NOT NULL,
    last_error TEXT NOT NULL,
    held       BIGINT NOT NULL,
    failing    BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (device_id, folder)
);
CREATE INDEX device_folder_state_folder ON device_folder_state (folder);

-- What a computer is doing now, while it sends.
CREATE TABLE device_activity (
    device_id    BIGINT PRIMARY KEY REFERENCES devices(id),
    updated_at   BIGINT NOT NULL,
    phase        TEXT NOT NULL,
    current_file TEXT NOT NULL DEFAULT '',
    files_done   BIGINT NOT NULL DEFAULT 0,
    files_total  BIGINT NOT NULL DEFAULT 0,
    bytes_done   BIGINT NOT NULL DEFAULT 0,
    bytes_total  BIGINT NOT NULL DEFAULT 0,
    speed_bps    BIGINT NOT NULL DEFAULT 0
);

-- The paths of a device. A deleted path keeps its row (`deleted_at`; `deleted_by` is `web` or `rename`) until retention ends.
CREATE TABLE files (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id          BIGINT NOT NULL REFERENCES devices(id),
    path               TEXT NOT NULL,
    current_version_id BIGINT,
    deleted_at         BIGINT,
    deleted_by         TEXT,
    -- What the library shows it as, from its extension.
    media              TEXT GENERATED ALWAYS AS (
        CASE
            WHEN lower(path) ~ '\.(jpg|jpeg|png|gif|webp|bmp|tif|tiff|heic|heif|avif)$' THEN 'image'
            WHEN lower(path) ~ '\.(mp4|mov|mkv|avi|webm|m4v|wmv|mts|3gp|mpg|mpeg)$' THEN 'video'
        END) STORED,
    UNIQUE (device_id, path)
);
CREATE INDEX files_current_version ON files (current_version_id);
CREATE INDEX files_deleted ON files (deleted_at DESC) WHERE deleted_at IS NOT NULL;
CREATE INDEX files_path_prefix ON files (device_id, path text_pattern_ops);
CREATE INDEX files_path_search ON files USING gin (path public.gin_trgm_ops);
-- A folder holds one spelling of a name whatever the case, so a commit looks for the same path or folder in another case.
CREATE INDEX files_folded ON files (device_id, lower(path) text_pattern_ops) WHERE deleted_at IS NULL;
CREATE INDEX files_library ON files (id) WHERE deleted_at IS NULL AND media IS NOT NULL;

CREATE TABLE versions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id    UUID NOT NULL REFERENCES files(id),
    root_hash  BYTEA NOT NULL,
    size       BIGINT NOT NULL,
    mtime      BIGINT NOT NULL,
    mode       BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    pruned_at  BIGINT
);
CREATE INDEX versions_file ON versions (file_id, id);
CREATE INDEX versions_root ON versions (root_hash);
CREATE INDEX versions_pruned ON versions (pruned_at) WHERE pruned_at IS NOT NULL;

-- The change log shown in the web app.
CREATE TABLE events (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id),
    path      TEXT NOT NULL,
    action    TEXT NOT NULL,
    ts        BIGINT NOT NULL,
    hash      TEXT,
    detail    TEXT
);
CREATE INDEX events_device ON events (device_id, id);
CREATE INDEX events_path ON events (device_id, path, id DESC);
CREATE INDEX events_ts ON events (ts);

-- What was read from a content (once per content, not per file): kind, size, time and place, EXIF.
CREATE TABLE file_meta (
    root_hash   BYTEA PRIMARY KEY,
    mime        TEXT NOT NULL,
    read_at     BIGINT NOT NULL,
    kind        TEXT,
    width       BIGINT,
    height      BIGINT,
    duration_ms BIGINT,
    poster_ms   BIGINT,
    codec       TEXT,
    taken_at    BIGINT,
    lat         DOUBLE PRECISION,
    lon         DOUBLE PRECISION,
    exif        TEXT,
    caption     TEXT,
    keywords    TEXT
);
CREATE INDEX file_meta_placed ON file_meta (root_hash) WHERE lat IS NOT NULL;

-- What a user says about a file: favorite, archive, rating, description, corrected date and place.
CREATE TABLE file_state (
    user_id     BIGINT NOT NULL REFERENCES users(id),
    file_id     UUID NOT NULL REFERENCES files(id) ON DELETE CASCADE,
    favorite    BOOLEAN NOT NULL DEFAULT FALSE,
    archived    BOOLEAN NOT NULL DEFAULT FALSE,
    rating      SMALLINT CHECK (rating >= 1 AND rating <= 5),
    description TEXT NOT NULL DEFAULT '',
    taken_at    BIGINT,
    lat         DOUBLE PRECISION,
    lon         DOUBLE PRECISION,
    updated_at  BIGINT NOT NULL,
    PRIMARY KEY (user_id, file_id),
    CONSTRAINT file_state_position CHECK ((lat IS NULL) = (lon IS NULL))
);
CREATE INDEX file_state_file ON file_state (file_id);
CREATE INDEX file_state_favorite ON file_state (file_id) WHERE favorite;
CREATE INDEX file_state_archived ON file_state (file_id) WHERE archived;
CREATE INDEX file_state_placed ON file_state (file_id) WHERE lat IS NOT NULL;

CREATE TABLE tags (
    id      UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id BIGINT NOT NULL REFERENCES users(id),
    name    TEXT NOT NULL CHECK (length(name) >= 1 AND length(name) <= 64)
);
CREATE UNIQUE INDEX tags_name ON tags (user_id, lower(name));

CREATE TABLE file_tags (
    file_id UUID NOT NULL REFERENCES files(id) ON DELETE CASCADE,
    tag_id  UUID NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    PRIMARY KEY (file_id, tag_id)
);
CREATE INDEX file_tags_tag ON file_tags (tag_id);

-- An album is a shortcut to a folder of a device (`folder_prefix` empty for the whole device): what is in the folder is in it.
CREATE TABLE albums (
    id               UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id          BIGINT NOT NULL REFERENCES users(id),
    folder_device_id BIGINT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    folder_prefix    TEXT NOT NULL,
    name             TEXT NOT NULL CHECK (length(name) >= 1 AND length(name) <= 120),
    description      TEXT NOT NULL DEFAULT '',
    cover_file_id    UUID REFERENCES files(id) ON DELETE SET NULL,
    created_at       BIGINT NOT NULL,
    updated_at       BIGINT NOT NULL
);
CREATE INDEX albums_user ON albums (user_id);
CREATE UNIQUE INDEX albums_folder ON albums (user_id, folder_device_id, folder_prefix);

-- Background work: photo metadata, pictures, video copies. Claimed with FOR UPDATE SKIP LOCKED; `seq` is the queue order.
CREATE TABLE jobs (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    seq         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    kind        TEXT NOT NULL,
    payload     TEXT NOT NULL,
    note        TEXT,
    status      TEXT NOT NULL DEFAULT 'queued',
    attempts    BIGINT NOT NULL DEFAULT 0,
    run_after   BIGINT NOT NULL DEFAULT 0,
    created_at  BIGINT NOT NULL,
    started_at  BIGINT,
    finished_at BIGINT,
    error       TEXT
);
CREATE INDEX jobs_status ON jobs (status, kind);
CREATE INDEX jobs_due ON jobs (run_after) WHERE status = 'queued';
CREATE INDEX jobs_queue ON jobs ((kind = 'proxy'), seq) WHERE status = 'queued';

CREATE TABLE alerts (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    kind        TEXT NOT NULL,
    key         TEXT NOT NULL DEFAULT '',
    message     TEXT NOT NULL,
    created_at  BIGINT NOT NULL,
    updated_at  BIGINT,
    resolved_at BIGINT
);
CREATE UNIQUE INDEX alerts_open ON alerts (kind, key) WHERE resolved_at IS NULL;
CREATE INDEX alerts_resolved ON alerts (resolved_at) WHERE resolved_at IS NOT NULL;

CREATE TABLE settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);

-- A source reads a storage or a module's kind of source on a schedule and writes into a folder (`device_id` and `folder_prefix`).
CREATE TABLE sources (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES users(id),
    name          TEXT NOT NULL CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$'),
    kind          TEXT NOT NULL,
    config        TEXT NOT NULL,
    device_id     BIGINT NOT NULL REFERENCES devices(id),
    folder_prefix TEXT NOT NULL DEFAULT '',
    interval_secs BIGINT NOT NULL DEFAULT 86400,
    enabled       BIGINT NOT NULL DEFAULT 1,
    run_requested BIGINT NOT NULL DEFAULT 0,
    last_run_at   BIGINT,
    last_ok_at    BIGINT,
    last_status   TEXT,
    last_message  TEXT,
    created_at    BIGINT NOT NULL
);
CREATE UNIQUE INDEX sources_user_name ON sources (user_id, name);

-- What a source collected: the remote id (or key) -> the path below its folder and the version marker. `removed_in_web_app`: it
-- stays deleted until it changes at the source.
CREATE TABLE source_items (
    source_id          BIGINT NOT NULL REFERENCES sources(id) ON DELETE CASCADE,
    remote_id          TEXT NOT NULL,
    path               TEXT NOT NULL,
    remote_version     TEXT NOT NULL,
    removed_in_web_app BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (source_id, remote_id)
);

-- Offsite copies, driven by rclone. `options` is a JSON object of backend options; a backup is compressed and encrypted.
CREATE TABLE mirrors (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL UNIQUE CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$'),
    kind           TEXT NOT NULL DEFAULT 'replica',
    remote         TEXT NOT NULL DEFAULT '',
    remote_type    TEXT NOT NULL,
    remote_path    TEXT NOT NULL,
    options        TEXT NOT NULL,
    scope          TEXT NOT NULL DEFAULT '',
    crypt_password TEXT NOT NULL DEFAULT '',
    crypt_salt     TEXT NOT NULL DEFAULT '',
    interval_secs  BIGINT NOT NULL DEFAULT 259200,
    keep_runs      BIGINT NOT NULL DEFAULT 3,
    enabled        BIGINT NOT NULL DEFAULT 1,
    run_requested  BIGINT NOT NULL DEFAULT 0,
    last_run_at    BIGINT,
    last_ok_at     BIGINT,
    last_status    TEXT,
    last_message   TEXT,
    last_files     BIGINT,
    last_bytes     BIGINT,
    created_at     BIGINT NOT NULL
);

CREATE TABLE mirror_items (
    mirror_id BIGINT NOT NULL REFERENCES mirrors(id) ON DELETE CASCADE,
    device_id BIGINT NOT NULL,
    path      TEXT NOT NULL,
    root_hash BYTEA NOT NULL,
    PRIMARY KEY (mirror_id, device_id, path)
);

