-- A device is a device and a folder holds files: they were one table. Now `devices` holds the devices (the token, the host, the
-- lease) and `folders` holds the folders: those of a user (`user`), the master folders (`master`), and one for each directory a
-- device sends (`backup`, with its device in `device_id`). The paths of a file are relative to its folder, which is named by its
-- `key` (`<user>/<name>`, `master:<name>`, `<user>/<device>/<directory>`); on disk nothing moves.

