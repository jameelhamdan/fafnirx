-- The devices: the rows of kind `device`, with the same ids.
CREATE TABLE devices (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id),
    name           TEXT NOT NULL,
    key            TEXT NOT NULL,
    token_hash     TEXT NOT NULL,
    created_at     BIGINT NOT NULL,
    revoked_at     BIGINT,
    -- Which installation of the client holds the device now (see the lease in `devices/grpc`).
    instance_id    TEXT,
    hostname       TEXT,
    os             TEXT,
    ip             TEXT,
    client_version TEXT,
    disk_total     BIGINT,
    disk_free      BIGINT,
    last_seen      BIGINT,
    CONSTRAINT devices_name_slug CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$' AND name !~ '^(con|prn|aux|nul|com[0-9]|lpt[0-9])(\.|$)')
);
CREATE UNIQUE INDEX devices_key ON devices (key);
CREATE UNIQUE INDEX devices_user_name ON devices (user_id, name);
CREATE UNIQUE INDEX devices_token ON devices (token_hash);
