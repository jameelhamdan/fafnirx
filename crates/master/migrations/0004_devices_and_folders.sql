-- A user's devices and folders share one directory, `files/users/<user>/`, so they never share a name.
CREATE FUNCTION device_name_is_free() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM folders WHERE kind = 'user' AND user_id = NEW.user_id AND name = NEW.name) THEN
        RAISE EXCEPTION 'there is a device or folder called % already', NEW.name;
    END IF;
    RETURN NEW;
END $$;
CREATE FUNCTION folder_name_is_free() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.kind = 'user' AND EXISTS (SELECT 1 FROM devices WHERE user_id = NEW.user_id AND name = NEW.name) THEN
        RAISE EXCEPTION 'there is a device or folder called % already', NEW.name;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER devices_name_free BEFORE INSERT OR UPDATE OF name ON devices FOR EACH ROW EXECUTE FUNCTION device_name_is_free();
CREATE TRIGGER folders_name_free BEFORE INSERT OR UPDATE OF name ON folders FOR EACH ROW EXECUTE FUNCTION folder_name_is_free();

-- The key of a folder, made from its names.
CREATE FUNCTION folders_set_key() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.key := CASE NEW.kind
        WHEN 'master' THEN 'master:' || NEW.name
        WHEN 'user' THEN (SELECT name FROM users WHERE id = NEW.user_id) || '/' || NEW.name
        ELSE (SELECT key FROM devices WHERE id = NEW.device_id) || '/' || NEW.name
    END;
    RETURN NEW;
END $$;
CREATE TRIGGER folders_key BEFORE INSERT ON folders FOR EACH ROW EXECUTE FUNCTION folders_set_key();
CREATE TRIGGER folders_key_renamed BEFORE UPDATE OF name ON folders FOR EACH ROW EXECUTE FUNCTION folders_set_key();

CREATE FUNCTION devices_set_key() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.key := (SELECT name FROM users WHERE id = NEW.user_id) || '/' || NEW.name;
    RETURN NEW;
END $$;
CREATE TRIGGER devices_key BEFORE INSERT ON devices FOR EACH ROW EXECUTE FUNCTION devices_set_key();

CREATE FUNCTION owner_is_fixed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN
        RAISE EXCEPTION 'the owner of a device or folder cannot change';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER devices_owner_fixed BEFORE UPDATE OF user_id ON devices FOR EACH ROW EXECUTE FUNCTION owner_is_fixed();
CREATE TRIGGER folders_owner_fixed BEFORE UPDATE OF user_id ON folders FOR EACH ROW EXECUTE FUNCTION owner_is_fixed();

-- The one rule for what a user sees of the folders: everything (an administrator), the master folders, their own, and the folders
-- they were added to. Every query that scopes by user calls this.
CREATE FUNCTION visible(f folders, uid BIGINT, everything BOOLEAN) RETURNS BOOLEAN LANGUAGE sql STABLE AS
$$ SELECT everything OR f.kind = 'master' OR f.user_id = uid
       OR EXISTS (SELECT 1 FROM shared_members m JOIN users o ON o.id = f.user_id
                  WHERE m.folder_id = f.id AND m.user_id = uid AND o.disabled_at IS NULL) $$;
