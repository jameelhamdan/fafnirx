-- Each directory of a device is a folder of its own: the first part of the paths it sent.
ALTER TABLE folders ADD COLUMN device_id BIGINT REFERENCES devices(id);
UPDATE folders SET kind = 'user' WHERE kind = 'local';
INSERT INTO folders (user_id, device_id, name, kind, key, token_hash, created_at, last_collected, totals_stale)
SELECT d.user_id, d.id, p.name, 'backup', d.key || '/' || p.name, '!', d.created_at, (SELECT o.last_collected FROM folders o WHERE o.id = d.id), TRUE
FROM devices d
JOIN (SELECT folder_id, split_part(path, '/', 1) AS name FROM files
      UNION SELECT folder_id, split_part(path, '/', 1) FROM events WHERE position('/' IN path) > 0
      UNION SELECT folder_id, split_part(path, '/', 1) FROM link_items) p ON p.folder_id = d.id
WHERE p.name <> '';

-- What a device sent moves to the folder of its directory, without the directory in its path.
UPDATE files f SET folder_id = b.id, path = substr(f.path, length(b.name) + 2)
FROM folders b WHERE b.kind = 'backup' AND b.device_id = f.folder_id AND starts_with(f.path, b.name || '/');
UPDATE events e SET folder_id = b.id, path = substr(e.path, length(b.name) + 2),
                    detail = CASE WHEN e.action = 'rename' AND starts_with(e.detail, b.name || '/') THEN substr(e.detail, length(b.name) + 2) ELSE e.detail END
FROM folders b WHERE b.kind = 'backup' AND b.device_id = e.folder_id AND starts_with(e.path, b.name || '/');
UPDATE link_items i SET folder_id = b.id, path = substr(i.path, length(b.name) + 2)
FROM folders b WHERE b.kind = 'backup' AND b.device_id = i.folder_id AND starts_with(i.path, b.name || '/');

-- A job names the folder and the path in it.
UPDATE jobs j SET payload = ((j.payload::jsonb - 'device') || jsonb_build_object('folder', b.key, 'path', substr(j.payload::jsonb ->> 'path', length(b.name) + 2)))::text
FROM folders b WHERE b.kind = 'backup' AND b.device_id IS NOT NULL
  AND j.payload::jsonb ->> 'device' = (SELECT key FROM devices WHERE id = b.device_id)
  AND starts_with(j.payload::jsonb ->> 'path', b.name || '/');
UPDATE jobs SET payload = ((payload::jsonb - 'device') || jsonb_build_object('folder', payload::jsonb -> 'device'))::text
WHERE payload::jsonb ? 'device';

