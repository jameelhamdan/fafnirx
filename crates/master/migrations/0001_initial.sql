-- 0001: the schema of the master as first released. Migrations are applied in order, once each, by every master
-- process on start (see src/platform/migrations.rs). Never edit a migration that has been released: add a new one.
-- This one is idempotent so that a database made before migrations were recorded is adopted as it is.
-- All integers are BIGINT: unix timestamps, sizes and nanosecond mtimes do not fit in 32 bits.

CREATE TABLE IF NOT EXISTS devices (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL UNIQUE,   -- slug; the folder of the device is files/<name>/
    kind           TEXT NOT NULL DEFAULT 'device',  -- device (a client) | source (imported by the master) | local (uploaded or dropped into files/)
    token_hash     TEXT NOT NULL,          -- hex sha256 of the device token
    created_at     BIGINT NOT NULL,
    revoked_at     BIGINT,
    hostname       TEXT,
    os             TEXT,
    ip             TEXT,
    client_version TEXT,
    disk_total     BIGINT,
    disk_free      BIGINT,
    last_seen      BIGINT,                 -- last heartbeat or upload
    last_collected BIGINT,                 -- last committed version
    CONSTRAINT devices_kind CHECK (kind IN ('device', 'source', 'local')),
    -- Lowercase so that it is the same folder on every file system, and not a name Windows reserves.
    CONSTRAINT devices_name_slug CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$'
                                        AND name !~ '^(con|prn|aux|nul|com[0-9]|lpt[0-9])(\.|$)')
);

-- The name is the folder on disk, so it cannot change.
CREATE OR REPLACE FUNCTION devices_name_is_fixed() RETURNS trigger AS $$
BEGIN
    IF NEW.name <> OLD.name THEN
        RAISE EXCEPTION 'the name of a device cannot change';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS devices_name_fixed ON devices;
CREATE TRIGGER devices_name_fixed BEFORE UPDATE OF name ON devices
    FOR EACH ROW EXECUTE FUNCTION devices_name_is_fixed();

-- What a device is doing right now, from its latest heartbeat. No row while it is idle.
CREATE TABLE IF NOT EXISTS device_activity (
    device_id    BIGINT PRIMARY KEY REFERENCES devices(id),
    updated_at   BIGINT NOT NULL,
    phase        TEXT NOT NULL,            -- scanning | hashing | uploading
    current_file TEXT NOT NULL DEFAULT '',
    files_done   BIGINT NOT NULL DEFAULT 0,
    files_total  BIGINT NOT NULL DEFAULT 0,
    bytes_done   BIGINT NOT NULL DEFAULT 0,
    bytes_total  BIGINT NOT NULL DEFAULT 0,
    speed_bps    BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS files (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id          BIGINT NOT NULL REFERENCES devices(id),
    path               TEXT NOT NULL,
    current_version_id BIGINT,
    deleted_at         BIGINT,
    deleted_by         TEXT,                      -- admin when deleted in the web app: the device no longer re-sends it
    UNIQUE (device_id, path)
);

CREATE TABLE IF NOT EXISTS versions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    file_id    BIGINT NOT NULL REFERENCES files(id),
    root_hash  BYTEA NOT NULL,
    size       BIGINT NOT NULL,
    mtime      BIGINT NOT NULL,            -- unix nanoseconds
    mode       BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    pruned_at  BIGINT                      -- set when beyond the version count
);
CREATE INDEX IF NOT EXISTS versions_file ON versions(file_id, id);
CREATE INDEX IF NOT EXISTS versions_root ON versions(root_hash);

CREATE TABLE IF NOT EXISTS events (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL REFERENCES devices(id),
    path      TEXT NOT NULL,
    action    TEXT NOT NULL,               -- add | update | delete | rename
    ts        BIGINT NOT NULL,
    hash      TEXT,
    detail    TEXT                         -- e.g. old path of a rename
);
CREATE INDEX IF NOT EXISTS events_device ON events(device_id, id);

CREATE TABLE IF NOT EXISTS alerts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        TEXT NOT NULL,             -- device_offline | upload_error | disk_usage | source_failed | mirror_failed
    key         TEXT NOT NULL DEFAULT '',  -- e.g. device name
    message     TEXT NOT NULL,
    created_at  BIGINT NOT NULL,
    updated_at  BIGINT,                    -- last time the problem was reported again
    resolved_at BIGINT
);
CREATE UNIQUE INDEX IF NOT EXISTS alerts_open ON alerts(kind, key) WHERE resolved_at IS NULL;

-- Third-party sources collected by the master itself. Each has a devices row (kind = 'source', named
-- source-<name>) that owns its files under files/source-<name>/.
CREATE TABLE IF NOT EXISTS sources (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$'),
    kind          TEXT NOT NULL,           -- gdrive
    config        TEXT NOT NULL,           -- JSON, includes credentials
    interval_secs BIGINT NOT NULL DEFAULT 86400,
    enabled       BIGINT NOT NULL DEFAULT 1,
    device_id     BIGINT NOT NULL REFERENCES devices(id),
    run_requested BIGINT NOT NULL DEFAULT 0,
    last_run_at   BIGINT,
    last_ok_at    BIGINT,
    last_status   TEXT,                    -- running | ok | partial | failed
    last_message  TEXT,
    created_at    BIGINT NOT NULL
);

-- What the master already imported from a source: remote id -> path and version marker.
CREATE TABLE IF NOT EXISTS source_items (
    source_id      BIGINT NOT NULL REFERENCES sources(id) ON DELETE CASCADE,
    remote_id      TEXT NOT NULL,
    path           TEXT NOT NULL,
    remote_version TEXT NOT NULL,
    PRIMARY KEY (source_id, remote_id)
);

-- Offsite mirrors, driven by rclone. `options` is a JSON object of rclone backend options.
CREATE TABLE IF NOT EXISTS mirrors (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$'),
    remote_type   TEXT NOT NULL,           -- rclone backend: s3, sftp, local, ...
    options       TEXT NOT NULL,           -- JSON, includes credentials
    remote_path   TEXT NOT NULL,           -- bucket/prefix inside the remote
    interval_secs BIGINT NOT NULL DEFAULT 259200,
    keep_runs     BIGINT NOT NULL DEFAULT 3,
    enabled       BIGINT NOT NULL DEFAULT 1,
    run_requested BIGINT NOT NULL DEFAULT 0,
    last_run_at   BIGINT,
    last_ok_at    BIGINT,
    last_status   TEXT,                    -- running | ok | partial | failed
    last_message  TEXT,
    last_files    BIGINT,
    last_bytes    BIGINT,
    created_at    BIGINT NOT NULL
);

-- What is already on the mirror: the root hash of each file as last uploaded.
CREATE TABLE IF NOT EXISTS mirror_items (
    mirror_id BIGINT NOT NULL REFERENCES mirrors(id) ON DELETE CASCADE,
    device_id BIGINT NOT NULL,
    path      TEXT NOT NULL,
    root_hash BYTEA NOT NULL,
    PRIMARY KEY (mirror_id, device_id, path)
);

-- What is known about a content (by root hash), whichever file holds it: kind, image size, EXIF.
CREATE TABLE IF NOT EXISTS file_meta (
    root_hash BYTEA PRIMARY KEY,
    mime      TEXT NOT NULL,
    width     BIGINT,
    height    BIGINT,
    taken_at  BIGINT,                      -- unix seconds, from EXIF when there is one
    exif      TEXT,                        -- JSON object of the EXIF fields worth showing
    read_at   BIGINT NOT NULL,
    kind        TEXT,                      -- image | video
    duration_ms BIGINT,                    -- videos
    codec       TEXT,                      -- videos: the video codec
    lat         DOUBLE PRECISION,          -- from the GPS tags
    lon         DOUBLE PRECISION
);

-- The photo library: what people say about a file, kept apart from the file itself (originals are never
-- touched). Everything is keyed by the file (a path of a device), so it survives new versions of the file.
-- Deleting a file for good (retention) removes its rows here.
CREATE TABLE IF NOT EXISTS file_state (
    file_id     BIGINT PRIMARY KEY REFERENCES files(id) ON DELETE CASCADE,
    favorite    BOOLEAN NOT NULL DEFAULT FALSE,
    archived    BOOLEAN NOT NULL DEFAULT FALSE,
    rating      SMALLINT CHECK (rating BETWEEN 1 AND 5),
    description TEXT NOT NULL DEFAULT '',
    taken_at    BIGINT,                    -- replaces the date from EXIF (or the modification time)
    lat         DOUBLE PRECISION,          -- replaces the GPS position from EXIF
    lon         DOUBLE PRECISION,
    updated_at  BIGINT NOT NULL,
    CONSTRAINT file_state_position CHECK ((lat IS NULL) = (lon IS NULL))
);

CREATE TABLE IF NOT EXISTS tags (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 64)
);
CREATE UNIQUE INDEX IF NOT EXISTS tags_name ON tags(lower(name));

CREATE TABLE IF NOT EXISTS file_tags (
    file_id BIGINT NOT NULL REFERENCES files(id) ON DELETE CASCADE,
    tag_id  BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    PRIMARY KEY (file_id, tag_id)
);
CREATE INDEX IF NOT EXISTS file_tags_tag ON file_tags(tag_id);

CREATE TABLE IF NOT EXISTS albums (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL CHECK (length(name) BETWEEN 1 AND 120),
    description   TEXT NOT NULL DEFAULT '',
    cover_file_id BIGINT REFERENCES files(id) ON DELETE SET NULL,
    created_at    BIGINT NOT NULL,
    updated_at    BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS album_files (
    album_id BIGINT NOT NULL REFERENCES albums(id) ON DELETE CASCADE,
    file_id  BIGINT NOT NULL REFERENCES files(id) ON DELETE CASCADE,
    added_at BIGINT NOT NULL,
    PRIMARY KEY (album_id, file_id)
);
CREATE INDEX IF NOT EXISTS album_files_file ON album_files(file_id);

-- Background work for the worker role. Claimed with FOR UPDATE SKIP LOCKED, so any number of workers can run.
CREATE TABLE IF NOT EXISTS jobs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       TEXT NOT NULL,              -- meta | proxy
    payload    TEXT NOT NULL,              -- JSON
    status     TEXT NOT NULL DEFAULT 'queued',  -- queued | running | failed
    attempts   BIGINT NOT NULL DEFAULT 0,
    run_after  BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL,
    error      TEXT
);
CREATE INDEX IF NOT EXISTS jobs_due ON jobs(run_after) WHERE status = 'queued';

CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
