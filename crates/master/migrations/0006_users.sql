-- 0006: users and workspaces. (Written for a master that holds no data yet: nothing is carried over from before users.)
-- Every device belongs to a user and lives in files/<user>/<device>/. Files that belong to nobody ("master files": uploaded by
-- hand, dropped in by SMB or any other means) live in the root of files/ and are held by one internal device row (kind
-- 'master', id 0, folder '_master') so that they use the same tables as everything else.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE,    -- slug; the folder of the user is files/<name>/, so it cannot change
    role          TEXT NOT NULL,           -- admin | normal | readonly
    password_hash TEXT NOT NULL,           -- argon2 PHC string; '!' = no password yet (cannot log in)
    created_at    BIGINT NOT NULL,
    disabled_at   BIGINT,
    CONSTRAINT users_role CHECK (role IN ('admin', 'normal', 'readonly')),
    -- Lowercase so that it is the same folder on every file system, and not a name Windows reserves.
    -- A leading letter or digit keeps the names starting with '_' (the master's) for the master.
    CONSTRAINT users_name_slug CHECK (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$'
                                      AND name !~ '^(con|prn|aux|nul|com[0-9]|lpt[0-9])(\.|$)')
);

CREATE OR REPLACE FUNCTION users_name_is_fixed() RETURNS trigger AS $$
BEGIN
    IF NEW.name <> OLD.name THEN
        RAISE EXCEPTION 'the name of a user cannot change';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER users_name_fixed BEFORE UPDATE OF name ON users
    FOR EACH ROW EXECUTE FUNCTION users_name_is_fixed();

-- The default administrator. It has no password until the master sets it from FAFNIRX_ADMIN_PASSWORD at start.
INSERT INTO users (name, role, password_hash, created_at)
VALUES ('admin', 'admin', '!', EXTRACT(EPOCH FROM now())::BIGINT);

-- Logins. Only the hash of the token is kept, so that a copy of the database cannot be used to log in.
CREATE TABLE sessions (
    token_hash TEXT PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX sessions_user ON sessions (user_id);
CREATE INDEX sessions_expires ON sessions (expires_at);

-- Devices: owned by a user. The name is unique per user; `folder` (<user>/<name>) is unique and is what the files are
-- stored under and what the API calls a device.
ALTER TABLE devices
    ADD COLUMN user_id BIGINT REFERENCES users(id),
    ADD COLUMN folder  TEXT;

ALTER TABLE devices DROP CONSTRAINT devices_name_key;
ALTER TABLE devices DROP CONSTRAINT devices_kind;
ALTER TABLE devices DROP CONSTRAINT devices_name_slug;
ALTER TABLE devices ADD CONSTRAINT devices_kind CHECK (kind IN ('device', 'source', 'local', 'master'));
ALTER TABLE devices ADD CONSTRAINT devices_name_slug CHECK (
    kind = 'master'
    OR (name ~ '^[a-z0-9][a-z0-9._-]{0,62}$' AND name !~ '^(con|prn|aux|nul|com[0-9]|lpt[0-9])(\.|$)'));
-- Nobody owns the master files, and everything else is owned.
ALTER TABLE devices ADD CONSTRAINT devices_owner CHECK ((kind = 'master') = (user_id IS NULL));

-- A source is named per user, not for the whole master: its device is called source-<name> and a user has one device of a
-- name, so the same source name can be used by several users.
ALTER TABLE sources DROP CONSTRAINT sources_name_key;

-- The folder is made from the owner and the name, which neither change.
CREATE OR REPLACE FUNCTION devices_set_folder() RETURNS trigger AS $$
BEGIN
    IF NEW.kind = 'master' THEN
        NEW.folder := '_master';
    ELSE
        NEW.folder := (SELECT name FROM users WHERE id = NEW.user_id) || '/' || NEW.name;
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER devices_folder BEFORE INSERT ON devices
    FOR EACH ROW EXECUTE FUNCTION devices_set_folder();

CREATE OR REPLACE FUNCTION devices_owner_is_fixed() RETURNS trigger AS $$
BEGIN
    IF NEW.user_id IS DISTINCT FROM OLD.user_id THEN
        RAISE EXCEPTION 'the owner of a device cannot change';
    END IF;
    RETURN NEW;
END $$ LANGUAGE plpgsql;
CREATE TRIGGER devices_owner_fixed BEFORE UPDATE OF user_id ON devices
    FOR EACH ROW EXECUTE FUNCTION devices_owner_is_fixed();

-- The master files: one internal device, id 0 (the identity of the others starts at 1).
INSERT INTO devices (id, name, kind, token_hash, created_at)
OVERRIDING SYSTEM VALUE
VALUES (0, '_master', 'master', '!', EXTRACT(EPOCH FROM now())::BIGINT);

ALTER TABLE devices ALTER COLUMN folder SET NOT NULL;
CREATE UNIQUE INDEX devices_user_name ON devices (user_id, name);
CREATE UNIQUE INDEX devices_folder ON devices (folder);

-- What people say about files is their own: albums, tags and the library state (favorite, archive, rating, description,
-- date and place). Master files are shared, so one user's favorite is not another's.
ALTER TABLE albums ADD COLUMN user_id BIGINT REFERENCES users(id);
ALTER TABLE albums ALTER COLUMN user_id SET NOT NULL;
CREATE INDEX albums_user ON albums (user_id);

ALTER TABLE tags ADD COLUMN user_id BIGINT REFERENCES users(id);
ALTER TABLE tags ALTER COLUMN user_id SET NOT NULL;
DROP INDEX tags_name;
CREATE UNIQUE INDEX tags_name ON tags (user_id, lower(name));

ALTER TABLE file_state ADD COLUMN user_id BIGINT REFERENCES users(id);
ALTER TABLE file_state ALTER COLUMN user_id SET NOT NULL;
ALTER TABLE file_state DROP CONSTRAINT file_state_pkey;
ALTER TABLE file_state ADD PRIMARY KEY (user_id, file_id);
CREATE INDEX file_state_file ON file_state (file_id);
